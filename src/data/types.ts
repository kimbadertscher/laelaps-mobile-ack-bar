// Shape of an alert event as the operator app receives it.
// Field names follow the backend contract from the brief: outcomes, requiresNote,
// product "camera_vlm" | "access_control", ackObservingAt.

export type Severity = "low" | "medium" | "high";

export type Product = "camera_vlm" | "access_control";

export type Outcome = {
  id: string;
  /** Fallback label from the backend. The UI shows t(`outcomes.<id>`) when a translation exists. */
  label: string;
  requiresNote: boolean;
};

export type Person = {
  id: string;
  name: string;
};

export type Detection = {
  label: string;
  confidence: number;
};

export type AckEvent = {
  id: string;
  product: Product;
  severity: Severity;
  /** Generated by the vision model or the access system, shown as delivered. */
  title: string;
  summary: string;
  site: string;
  zone: string;
  /** Camera or reader name, e.g. "CAM 04" or "Reader B2". */
  source: string;
  sourceDetail: string;
  occurredAt: string;
  detection: Detection | null;
  outcomes: Outcome[];
  /** Non-final "I am watching" marker. Only camera_vlm events can be observed. */
  ackObservingAt: string | null;
  ackObservingBy: Person | null;
  acknowledgedAt: string | null;
  acknowledgedBy: Person | null;
  acknowledgedOutcomeId: string | null;
  acknowledgedNote: string | null;
};

export type VoiceNote = {
  durationSec: number;
  audioUrl: string | null;
  transcript: string;
};

export type AckPayload = {
  outcomeId: string;
  note: string;
  voiceNote: VoiceNote | null;
};
